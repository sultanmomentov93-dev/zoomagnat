def db():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL не настроен")
    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        connect_timeout=10,
    )


def init_db():
    with db() as c:
        c.execute("""
            CREATE TABLE IF NOT EXISTS players(
                user_id BIGINT PRIMARY KEY,
                name TEXT NOT NULL,
                coins BIGINT NOT NULL DEFAULT 250,
                last_tick BIGINT NOT NULL,
                created_at BIGINT NOT NULL
            )
        """)
        c.execute("""
            CREATE TABLE IF NOT EXISTS animals(
                user_id BIGINT NOT NULL,
                animal_key TEXT NOT NULL,
                qty BIGINT NOT NULL DEFAULT 0,
                PRIMARY KEY(user_id, animal_key)
            )
        """)
        c.execute("""
            CREATE TABLE IF NOT EXISTS ledger(
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL,
                event TEXT NOT NULL,
                amount BIGINT NOT NULL,
                created_at BIGINT NOT NULL
            )
        """)
        c.execute("""
            CREATE TABLE IF NOT EXISTS reward_requests(
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL,
                amount BIGINT NOT NULL,
                status TEXT NOT NULL DEFAULT 'pending',
                created_at BIGINT NOT NULL
            )
        """)
        c.execute("""
            CREATE TABLE IF NOT EXISTS zoo_expansions(
                user_id BIGINT PRIMARY KEY,
                level INTEGER NOT NULL DEFAULT 1
            )
        """)
        c.execute("""
            CREATE TABLE IF NOT EXISTS test_wallets(
                user_id BIGINT PRIMARY KEY,
                test_usdt_cents BIGINT NOT NULL DEFAULT 0
            )
        """)
        c.execute("""
            CREATE TABLE IF NOT EXISTS test_ledger(
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL,
                event TEXT NOT NULL,
                amount_cents BIGINT NOT NULL,
                created_at BIGINT NOT NULL
            )
        """)
        
        c.execute("""
            CREATE TABLE IF NOT EXISTS referrals(
                invitee_id BIGINT PRIMARY KEY,
                inviter_id BIGINT NOT NULL,
                bonus BIGINT NOT NULL DEFAULT 100,
                created_at BIGINT NOT NULL,
                CHECK (invitee_id <> inviter_id)
            )
        """)


