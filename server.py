def validate_init_data(raw: str) -> dict:
    if not BOT_TOKEN:
        raise HTTPException(503, "BOT_TOKEN не настроен на сервере")
    if not raw:
        raise HTTPException(401, "Открой игру через Telegram")

    try:
        data = dict(urllib.parse.parse_qsl(raw, keep_blank_values=True))
        received_hash = data.pop("hash", None)
        if not received_hash:
            raise ValueError("no hash")

        check_string = "\n".join(
            f"{k}={v}" for k, v in sorted(data.items())
        )
        secret_key = hmac.new(
            b"WebAppData", BOT_TOKEN.encode(), hashlib.sha256
        ).digest()
        expected = hmac.new(
            secret_key, check_string.encode(), hashlib.sha256
        ).hexdigest()

        if not hmac.compare_digest(expected, received_hash):
            raise ValueError("bad hash")

        auth_date = int(data.get("auth_date", "0"))
        if time.time() - auth_date > 86400 or auth_date > time.time() + 60:
            raise ValueError("expired")

        user = json.loads(data.get("user", "{}"))
        if not isinstance(user.get("id"), int):
            raise ValueError("no user")
        return user
    except Exception:
        raise HTTPException(
            401, "Не удалось проверить авторизацию Telegram"
        )


def get_player(user):
    uid = user["id"]
    now = int(time.time())
    name = (user.get("first_name") or "Игрок")[:80]

    with db() as c:
        c.execute(
            """INSERT INTO players(user_id,name,coins,last_tick,created_at)
               VALUES(%s,%s,250,%s,%s)
               ON CONFLICT(user_id) DO NOTHING""",
            (uid, name, now, now),
        )
        row = c.execute(
            "SELECT * FROM players WHERE user_id=%s", (uid,)
        ).fetchone()

        elapsed = max(0, min(now - row["last_tick"], 8 * 3600))
        holdings = c.execute(
            "SELECT animal_key,qty FROM animals WHERE user_id=%s", (uid,)
        ).fetchall()

        income_per_minute = sum(
            ANIMALS[r["animal_key"]]["income"] * r["qty"]
            for r in holdings
        )
        earned = (elapsed // 60) * income_per_minute

        if earned:
            c.execute(
                "UPDATE players SET coins=coins+%s,last_tick=%s WHERE user_id=%s",
                (earned, now, uid),
            )
            c.execute(
                """INSERT INTO ledger(user_id,event,amount,created_at)
                   VALUES(%s,%s,%s,%s)""",
                (uid, "offline_income", earned, now),
            )
        else:
            c.execute(
                "UPDATE players SET last_tick=%s WHERE user_id=%s",
                (now, uid),
            )

        row = c.execute(
            "SELECT * FROM players WHERE user_id=%s", (uid,)
        ).fetchone()
        holdings = c.execute(
            "SELECT animal_key,qty FROM animals WHERE user_id=%s", (uid,)
        ).fetchall()
        
        c.execute(
            """INSERT INTO test_wallets(user_id, test_usdt_cents)
               VALUES(%s, 0)
               ON CONFLICT(user_id) DO NOTHING""",
            (uid,),
        )
        wallet = c.execute(
            "SELECT test_usdt_cents FROM test_wallets WHERE user_id=%s",
            (uid,),
        ).fetchone()

    
    qty_by_key = {r["animal_key"]: r["qty"] for r in holdings}

    animals = []
    for key, info in ANIMALS.items():
        qty = qty_by_key.get(key, 0)
        animals.append({"key": key, **info, "qty": qty})

    total_income = sum(a["income"] * a["qty"] for a in animals)
    return {
        "user_id": uid,
        "name": row["name"],
        "coins": row["coins"],
        "test_usdt": wallet["test_usdt_cents"] / 100,
        "exchange_rate": 10000,
        "income_per_minute": total_income,
        "animals": animals,
        "notice": "Игровые монеты не являются криптовалютой и пока не обмениваются на деньги.",
    }


def auth(authorization: Optional[str]):
    if not authorization or not authorization.startswith("tma "):
        raise HTTPException(401, "Открой игру из Telegram")
    return validate_init_data(authorization[4:])


